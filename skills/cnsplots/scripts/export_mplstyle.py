#!/usr/bin/env python3
"""Regenerate or check the bundled Cell style files against cnsplots.

Reads the Cell palette from the installed cnsplots package and derives:
- styles/cns_cell.mplstyle
- styles/cell_colors.py

The --check mode is the drift test: it exits non-zero when either bundled
file no longer matches cns.palettes("Cell").

Usage:
    python3 export_mplstyle.py --check   # drift test; exit 1 on drift
    python3 export_mplstyle.py --write   # regenerate both files
"""

from __future__ import annotations

import argparse
import difflib
import pathlib
import sys

import cnsplots as cns
import loguru
import matplotlib.colors as mcolors

logger = loguru.logger

SKILL_DIR = pathlib.Path(__file__).resolve().parent.parent
STYLE_PATH = SKILL_DIR / "styles" / "cns_cell.mplstyle"
COLORS_PATH = SKILL_DIR / "styles" / "cell_colors.py"

FONT_SANS_SERIF = "Arial, Helvetica, Nimbus Sans, Liberation Sans, DejaVu Sans"
SAVEFIG_DPI = 360
FIGURE_DPI = 360
CELL_NAMES = (
    "CELL_RED",
    "CELL_TEAL",
    "CELL_OCHRE",
    "CELL_SLATE",
    "CELL_SAGE",
    "CELL_SALMON",
    "CELL_PURPLE",
    "CELL_STEEL",
    "CELL_ROSE",
    "CELL_GREY",
)


def cell_hex() -> list[str]:
    """Return the installed cnsplots Cell palette as lowercase hex strings."""
    return [mcolors.to_hex(color).lower() for color in cns.palettes("Cell")]


def cell_rgb() -> list[tuple[float, float, float]]:
    """Return the installed cnsplots Cell palette as rounded RGB tuples."""
    colors: list[tuple[float, float, float]] = []
    for color in cns.palettes("Cell"):
        red, green, blue = color
        colors.append((round(red, 7), round(green, 7), round(blue, 7)))
    return colors


def build_mplstyle(hex_colors: list[str]) -> str:
    """Build cns_cell.mplstyle from the Cell hex values."""
    cycle = ", ".join(f"'{color.lstrip('#')}'" for color in hex_colors)
    return f"""# =============================================================================
# cnsplots - Cell Press Style Matplotlib Style Sheet
# Generated by scripts/export_mplstyle.py from cnsplots {cns.__version__}
# Cell palette. Do not edit by hand; run: python scripts/export_mplstyle.py --write
# =============================================================================

# Typography (Cell Press Arial-first; metric-compatible fallbacks for Linux)
font.family: sans-serif
font.sans-serif: {FONT_SANS_SERIF}
font.size: 8.0
mathtext.fontset: custom

# Axes & Spines (mirrors cnsplots settings)
axes.linewidth: 0.5
axes.labelsize: 8.0
axes.labelpad: 2.0
axes.titlesize: 8.0
axes.titleweight: bold
axes.titlelocation: center
axes.titlepad: 4.0
axes.spines.top: False
axes.spines.right: False
axes.edgecolor: black
axes.labelcolor: black
axes.xmargin: 0.05
axes.ymargin: 0.05
axes.grid: False

# Marker and patch geometry (matches cnsplots s=7 pt^2 and 0.5 pt edges)
lines.markersize: 2.65
patch.linewidth: 0.5

# Color cycle (Cell Press 10-color qualitative palette)
# In .mplstyle files, hex codes in cycler must omit the leading '#'.
axes.prop_cycle: cycler('color', [{cycle}])

# Continuous colormap (perceptually uniform)
image.cmap: viridis

# Ticks (compact, outward-facing)
xtick.labelsize: 7.0
xtick.major.size: 2.0
xtick.major.width: 0.6
xtick.major.pad: 1.0
xtick.color: black
xtick.bottom: True

ytick.labelsize: 7.0
ytick.major.size: 2.0
ytick.major.width: 0.6
ytick.major.pad: 1.0
ytick.color: black
ytick.left: True

# Legend (compact, unbordered)
legend.fontsize: 7.0
legend.title_fontsize: 8.0
legend.frameon: False
legend.handlelength: 0.7
legend.handleheight: 0.7
legend.handletextpad: 0.3
legend.markerscale: 0.5

# Figure canvas & vector export (360 dpi display/export, editable text, white background)
figure.dpi: {FIGURE_DPI}
savefig.dpi: {SAVEFIG_DPI}
savefig.bbox: tight
savefig.pad_inches: 0.01
savefig.transparent: False
pdf.fonttype: 42
svg.fonttype: none
"""


def build_cell_colors(
    hex_colors: list[str], rgb_colors: list[tuple[float, float, float]]
) -> str:
    """Build cell_colors.py from the Cell hex and RGB values."""
    hex_lines = "\n".join(
        f'    "{color}",  # {index}' for index, color in enumerate(hex_colors)
    )
    constant_lines = "\n".join(
        f"{name} = CELL_HEX[{index}]" for index, name in enumerate(CELL_NAMES)
    )
    rgb_lines = "\n".join(
        f"    ({red:.7f}, {green:.7f}, {blue:.7f})," for red, green, blue in rgb_colors
    )
    return f'''"""Cell Press color palette definitions for matplotlib / seaborn.

Generated by scripts/export_mplstyle.py from cnsplots {cns.__version__} Cell
palette. Do not edit by hand; run: python scripts/export_mplstyle.py --write
"""

from __future__ import annotations

# Cell Press 10-color qualitative palette (hex codes)
CELL_HEX: list[str] = [
{hex_lines}
]

# Named constants for semantic assignment
{constant_lines}

# RGB float tuples (0.0 to 1.0)
CELL_RGB: list[tuple[float, float, float]] = [
{rgb_lines}
]


def get_cell_colors(n: int | None = None) -> list[str]:
    """Return the first n colors of the Cell palette as hex strings."""
    if n is None or n >= len(CELL_HEX):
        return list(CELL_HEX)
    return list(CELL_HEX[:n])
'''


def build_outputs() -> dict[pathlib.Path, str]:
    """Build the expected contents of both generated style files."""
    hex_colors = cell_hex()
    rgb_colors = cell_rgb()
    return {
        STYLE_PATH: build_mplstyle(hex_colors),
        COLORS_PATH: build_cell_colors(hex_colors, rgb_colors),
    }


def check_files(expected: dict[pathlib.Path, str]) -> bool:
    """Compare expected contents with the files on disk and log drift."""
    clean = True
    for path, content in expected.items():
        if not path.is_file():
            logger.error(f"Missing generated file: {path}")
            clean = False
            continue
        actual = path.read_text(encoding="utf-8")
        if actual == content:
            logger.info(f"[OK] {path}")
            continue
        clean = False
        logger.error(f"[DRIFT] {path} differs from cnsplots {cns.__version__}")
        diff = difflib.unified_diff(
            actual.splitlines(),
            content.splitlines(),
            fromfile=str(path),
            tofile="expected",
            lineterm="",
        )
        for line in list(diff)[:20]:
            logger.error(line)
    return clean


def write_files(expected: dict[pathlib.Path, str]) -> None:
    """Write both generated style files to disk."""
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        logger.info(f"[WROTE] {path}")


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument(
        "--write", action="store_true", help="Regenerate both style files."
    )
    group.add_argument(
        "--check", action="store_true", help="Fail if either file drifts from cnsplots."
    )
    return parser.parse_args()


def main() -> int:
    """Regenerate or check the bundled Cell style files."""
    args = parse_args()
    try:
        expected = build_outputs()
        if args.write:
            write_files(expected)
            return 0
        return 0 if check_files(expected) else 1
    except (OSError, ValueError, AttributeError):
        logger.exception("Style export failed")
        return 1


if __name__ == "__main__":
    sys.exit(main())
